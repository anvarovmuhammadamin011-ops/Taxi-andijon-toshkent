const CYR_TO_LATIN: Record<string, string> = {
  "\u0430": "a", "\u0431": "b", "\u0432": "v", "\u0433": "g", "\u0434": "d",
  "\u0435": "e", "\u0451": "e", "\u0436": "j", "\u0437": "z", "\u0438": "i",
  "\u043A": "k", "\u043B": "l", "\u043C": "m", "\u043D": "n", "\u043E": "o",
  "\u043F": "p", "\u0440": "r", "\u0441": "s", "\u0442": "t", "\u0443": "u",
  "\u0444": "f", "\u0445": "x", "\u0446": "c", "\u0447": "ch", "\u0448": "sh",
  "\u0449": "sh", "\u044A": "", "\u044B": "i", "\u044C": "", "\u044D": "e",
  "\u044E": "yu", "\u044F": "ya", "\u0439": "y", "\u045E": "o", "\u049B": "q",
  "\u0493": "g", "\u04B3": "h", "\u2019": "'", "\u02BC": "'", "\u2018": "'",
};

export function toLatin(text: string): string {
  let out = "";
  for (const ch of (text ?? "").toLowerCase()) {
    out += CYR_TO_LATIN[ch] ?? ch;
  }
  return out;
}

