export function classifyPostKind(text: string): PostKind {
  const t = toLatin(text);
  if (DRIVER_PATTERNS.some((re) => re.test(t))) return "driver";
  if (PASSENGER_PATTERNS.some((re) => re.test(t))) return "passenger";
  return "other";
}
